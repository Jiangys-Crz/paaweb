/** Real multipart binding, mapper constraints and local storage, isolated from production data. */
@SpringJUnitConfig(FileUploadTests.Config.class)
class FileUploadTests {
    @Autowired private JdbcTemplate jdbc;
    @Autowired private FileSystemMapper mapper;
    @Autowired private FileStorageService storage;
    @Autowired private FileUploadService uploadService;
    @TempDir Path uploads;
    private MockMvc mvc;
    private MockHttpSession session;

    @BeforeEach
    void setUp() {
        jdbc.execute("DROP ALL OBJECTS");
        jdbc.execute("""
                CREATE TABLE file_system (
                    file_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    url VARCHAR(500) NOT NULL CONSTRAINT uk_file_url UNIQUE,
                    type VARCHAR(20) NOT NULL, name VARCHAR(255) NOT NULL,
                    uploader_id BIGINT NOT NULL, create_time TIMESTAMP NOT NULL,
                    storage_type VARCHAR(20), storage_key VARCHAR(1000),
                    access_purpose VARCHAR(32) NOT NULL DEFAULT 'GENERAL')
                """);
        ReflectionTestUtils.setField(storage, "uploadPath", uploads.toString());
        FileController controller = new FileController();
        ReflectionTestUtils.setField(controller, "fileSystemMapper", mapper);
        ReflectionTestUtils.setField(controller, "fileStorageService", storage);
        ReflectionTestUtils.setField(controller, "fileUploadService", uploadService);
        mvc = MockMvcBuilders.standaloneSetup(controller).setControllerAdvice(new GlobalExceptionHandler()).build();
        var user = new UserProfileVO();
        user.setUserId(8L);
        session = new MockHttpSession();
        session.setAttribute("user", user);
    }

    @ParameterizedTest
    @ValueSource(strings = {"certificate", "id_photo", "student_card", "school_logo", ""})
    void sharedImageUploadStoresTheAuthenticatedOwnerAndPurpose(String purpose) throws Exception {
        mvc.perform(multipart("/file/upload").file(image()).param("uploadType", purpose)
                        .param("uploaderId", "999").session(session))
                .andExpect(status().isOk()).andExpect(jsonPath("$.code").value(200));
        FileSystem saved = mapper.selectById(1L);
        assertThat(saved.getUploaderId()).isEqualTo(8L);
        assertThat(saved.getAccessPurpose()).isEqualTo("certificate".equals(purpose) ? "CERTIFICATE"
                : List.of("id_photo", "student_card").contains(purpose) ? "IDENTITY" : "GENERAL");
        assertThat(ImageIO.read(uploads.resolve(saved.getStorageKey()).toFile())).isNotNull();
        if ("student_card".equals(purpose)) {
            assertThat(saved.getStorageKey()).startsWith("sensitive/student_card/");
            assertThat(saved.getUrl()).isEqualTo("/file/image/1");
        }
    }

    @Test
    void studentCardUploadRejectsNonImagesBeforeStorage() throws Exception {
        mvc.perform(multipart("/file/upload").file(pdf(1)).param("uploadType", "student_card").session(session))
                .andExpect(jsonPath("$.code").value(400))
                .andExpect(jsonPath("$.msg").value("认证照片只能上传 PNG/JPG/JPEG 格式的图片文件"));
        assertNoStoredFiles();
    }

    @Test
    void parallelPrivateUploadsDoNotCollide() throws Exception {
        try (var executor = Executors.newFixedThreadPool(8)) {
            List<Callable<Integer>> requests = new ArrayList<>();
            for (int i = 0; i < 16; i++) {
                requests.add(() -> mvc.perform(multipart("/file/upload").file(image())
                                .param("uploadType", "certificate").session(session))
                        .andExpect(jsonPath("$.code").value(200)).andReturn().getResponse().getStatus());
            }
            for (var response : executor.invokeAll(requests)) assertThat(response.get()).isEqualTo(200);
        }
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM file_system", Integer.class)).isEqualTo(16);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM file_system WHERE url LIKE '/file/pending/%'", Integer.class)).isZero();
    }

    @Test
    void pdfTemplateMustHaveOnePageAndIsRegisteredAsPrivate() throws Exception {
        mvc.perform(multipart("/file/upload").file(pdf(2)).param("uploadType", "certificate_template").session(session))
                .andExpect(jsonPath("$.code").value(400));
        assertNoStoredFiles();
        mvc.perform(multipart("/file/upload").file(pdf(1)).param("uploadType", "certificate_template").session(session))
                .andExpect(jsonPath("$.code").value(200));
        FileSystem saved = mapper.selectById(1L);
        assertThat(saved.getAccessPurpose()).isEqualTo("TEMPLATE");
        assertThat(saved.getUrl()).isEqualTo("/file/image/1");
    }

    @Test
    void objectStorageUsesAProtectedUrlAndKeepsTheStorageKey() {
        Long id = uploadService.register(new FileStorageService.StoredFile(FileStorageService.OBJECT, "uploads/cloud.png"),
                "cloud.png", "png", null, 8L);
        FileSystem saved = mapper.selectById(id);
        assertThat(saved.getUrl()).isEqualTo("/file/image/" + id);
        assertThat(saved.getStorageKey()).isEqualTo("uploads/cloud.png");
        assertThat(saved.getAccessPurpose()).isEqualTo("GENERAL");
    }

    @Test
    void failedFinalUrlBindingRollsBackTheRecordAndDeletesTheStoredFile() throws Exception {
        jdbc.execute("ALTER TABLE file_system ADD CONSTRAINT reject_final_url CHECK (url NOT LIKE '/file/image/%')");
        mvc.perform(multipart("/file/upload").file(image()).param("uploadType", "certificate").session(session))
                .andExpect(jsonPath("$.code").value(500));
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM file_system", Integer.class)).isZero();
        assertNoStoredFiles();
    }

    @Test
    void missingFileMigrationGivesAnActionableErrorAndLeavesNoStoredFile() throws Exception {
        jdbc.execute("ALTER TABLE file_system DROP COLUMN access_purpose");
        mvc.perform(multipart("/file/upload").file(image()).param("uploadType", "certificate").session(session))
                .andExpect(jsonPath("$.code").value(500))
                .andExpect(jsonPath("$.msg").value("上传文件记录保存失败，请管理员检查文件表迁移和后端日志后重试"));
        assertNoStoredFiles();
    }

    @Test
    void invalidImageAndMissingFileAreRejectedBeforeStorage() throws Exception {
        mvc.perform(multipart("/file/upload")
                        .file(new MockMultipartFile("file", "bad.png", "image/png", new byte[]{1, 2, 3}))
                        .param("uploadType", "certificate").session(session))
                .andExpect(jsonPath("$.code").value(400));
        mvc.perform(multipart("/file/upload").session(session))
                .andExpect(status().isBadRequest()).andExpect(jsonPath("$.code").value(400));
        assertNoStoredFiles();
    }

    @Test
    void oversizedCertificateImageAndLongFilenameHaveSpecificErrors() throws Exception {
        mvc.perform(multipart("/file/upload")
                        .file(new MockMultipartFile("file", "large.png", "image/png", new byte[5 * 1024 * 1024 + 1]))
                        .param("uploadType", "certificate").session(session))
                .andExpect(jsonPath("$.code").value(413));
        mvc.perform(multipart("/file/upload")
                        .file(new MockMultipartFile("file", "a".repeat(256) + ".png", "image/png", new byte[]{1}))
                        .session(session)).andExpect(jsonPath("$.code").value(400));
        assertNoStoredFiles();
    }

    private void assertNoStoredFiles() throws Exception {
        try (var files = Files.walk(uploads)) { assertThat(files.filter(Files::isRegularFile).count()).isZero(); }
    }

    @Test
    void certificateUploadSucceedsEvenWhenAnOldPlaceholderRecordExists() throws Exception {
        jdbc.update("""
                INSERT INTO file_system(url, type, name, uploader_id, create_time, access_purpose)
                VALUES('/file/image/0', 'png', 'old.png', 8, CURRENT_TIMESTAMP, 'CERTIFICATE')
                """);
        mvc.perform(multipart("/file/upload").file(image()).param("uploadType", "certificate").session(session))
                .andExpect(status().isOk()).andExpect(jsonPath("$.code").value(200));
        FileSystem saved = mapper.selectById(2L);
        assertThat(saved.getUrl()).isEqualTo("/file/image/2");
        assertThat(saved.getAccessPurpose()).isEqualTo("CERTIFICATE");
        assertThat(Files.isRegularFile(uploads.resolve(saved.getStorageKey()))).isTrue();
    }

    private MockMultipartFile image() throws Exception {
        var output = new ByteArrayOutputStream();
        ImageIO.write(new BufferedImage(16, 16, BufferedImage.TYPE_INT_RGB), "png", output);
        return new MockMultipartFile("file", "证书.PNG", "image/png", output.toByteArray());
    }

    private MockMultipartFile pdf(int pages) throws Exception {
        try (PDDocument document = new PDDocument(); var output = new ByteArrayOutputStream()) {
            for (int i = 0; i < pages; i++) document.addPage(new PDPage());
            document.save(output);
            return new MockMultipartFile("file", "template.pdf", "application/pdf", output.toByteArray());
        }
    }

    @Configuration
    @EnableTransactionManagement
    @MapperScan(basePackageClasses = FileSystemMapper.class)
    static class Config {
        @Bean DataSource dataSource() {
            return new DriverManagerDataSource("jdbc:h2:mem:file-upload;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        }
        @Bean JdbcTemplate jdbcTemplate(DataSource dataSource) { return new JdbcTemplate(dataSource); }
        @Bean PlatformTransactionManager transactionManager(DataSource dataSource) {
            return new DataSourceTransactionManager(dataSource);
        }
        @Bean SqlSessionFactory sqlSessionFactory(DataSource dataSource) throws Exception {
            var factory = new MybatisSqlSessionFactoryBean();
            factory.setDataSource(dataSource);
            return factory.getObject();
        }
        @Bean FileStorageService storage() {
            SystemConfigService config = mock(SystemConfigService.class);
            when(config.getObjectStorageConfig()).thenReturn(new ObjectStorageConfigDTO());
            return new FileStorageService(config);
        }
        @Bean FileUploadService uploadService(FileSystemMapper mapper) { return new FileUploadService(mapper); }
    }
}
