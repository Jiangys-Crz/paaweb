    @Test void unchangedPushPayloadsAreIsolatedAndRejudgesUpdateOnlyTheirBoard() throws Exception {
        long second = create("第二外榜");
        pushProblem(7L, "历史题目"); pushProblem(second, "独立题目");
        push(7L, "account-a", "Accepted", "legacy-code");
        push(second, "account-a", "Wrong Answer", "new-code");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM submit_record", Integer.class)).isEqualTo(2);
        assertThat(jdbc.queryForObject("SELECT event_id FROM submit_record WHERE board_id=?", Long.class, second)).isEqualTo(7L);
        assertThat(jdbc.queryForObject("SELECT problem_name FROM submit_record WHERE board_id=?", String.class, second)).isEqualTo("独立题目");
        assertThat(jdbc.queryForObject("SELECT time_usage FROM submit_record WHERE board_id=?", Integer.class, second)).isEqualTo(12);
        push(second, "account-a", "Accepted", "updated-code");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM submit_record", Integer.class)).isEqualTo(2);
        assertThat(jdbc.queryForObject("SELECT code_content FROM submit_record WHERE board_id=7", String.class)).isEqualTo("legacy-code");
        assertThat(jdbc.queryForObject("SELECT code_content FROM submit_record WHERE board_id=?", String.class, second)).isEqualTo("updated-code");
        open(7L, "历史榜"); open(second, "独立榜");
        mvc.perform(get("/leaderboard/" + second)).andExpect(jsonPath("$.data.boardId").value(second))
            .andExpect(jsonPath("$.data.eventId").value(7)).andExpect(jsonPath("$.data.title").value("独立榜"))
            .andExpect(jsonPath("$.data.rows[0].solved").value(1));
        mvc.perform(get("/leaderboard/" + second + "/stats")).andExpect(jsonPath("$.data.totalSubmissions").value(1));
        assertThat(service.ratingBoardId(7L)).isEqualTo(7L);
    }

    @Test void renameAndDeletePreserveOtherBoardsAndParentSignups() throws Exception {
        long second = create("待改名");
        pushProblem(7L,"原题"); pushProblem(second,"新题");
        push(7L,"account-a","Accepted","old"); push(second,"account-a","Accepted","new");
        open(second, "新外榜名称");
        mvc.perform(get("/leaderboard/list")).andExpect(jsonPath("$.data.length()").value(1))
            .andExpect(jsonPath("$.data[0].name").value("新外榜名称")).andExpect(jsonPath("$.data[0].eventName").value("比赛甲"));
        mvc.perform(delete("/leaderboard/admin/boards/" + second)).andExpect(jsonPath("$.code").value(200));
        assertThat(jdbc.queryForObject("SELECT count(*) FROM event_problem WHERE board_id=?", Integer.class, second)).isZero();
        assertThat(jdbc.queryForObject("SELECT count(*) FROM submit_record WHERE board_id=?", Integer.class, second)).isZero();
        assertThat(jdbc.queryForObject("SELECT code_content FROM submit_record WHERE board_id=7", String.class)).isEqualTo("old");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM signup_personal WHERE event_id=7", Integer.class)).isEqualTo(2);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM event", Integer.class)).isEqualTo(2);
        mvc.perform(get("/leaderboard/" + second)).andExpect(status().isNotFound());
        mvc.perform(post("/external/board/" + second + "/problems").contentType("application/json")
            .content("{\"api_key\":\"test-key\",\"problems\":[{\"display_id\":\"A\",\"title\":\"deleted\"}]}"))
            .andExpect(jsonPath("$.code").value(500));
    }

    @Test void accountsStillResolveAgainstParentCompetitionAndClosedBoardsHideCode() throws Exception {
        long second = create("关闭榜"); pushProblem(second, "A");
        push(second, "other-event", "Accepted", "wrong-event");
        push(second, "pending-account", "Accepted", "pending");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM submit_record", Integer.class)).isZero();
        push(second, "account-a", "Accepted", "private-code");
        long submission = jdbc.queryForObject("SELECT submit_record_id FROM submit_record", Long.class);
        mvc.perform(get("/leaderboard/submission/" + submission + "/code")).andExpect(status().isForbidden());
        open(second, "开放榜");
        mvc.perform(get("/leaderboard/submission/" + submission + "/code")).andExpect(jsonPath("$.data.content").value("private-code"));
    }

    @Test void teamAndMemberAccountsBothResolveAgainstTheParentEvent() throws Exception {
        jdbc.update("UPDATE event SET is_team=1 WHERE event_id=7");
        jdbc.update("INSERT INTO signup_team(signup_id,event_id,team_name,status,contest_account,is_ranking,type) VALUES(91,7,'队伍','approved','team-a',1,'official')");
        jdbc.update("INSERT INTO signup_team_detail(detail_id,signup_team_id,user_id,member_order,contest_account) VALUES(1,91,9,1,'member-a')");
        long second = create("团队榜"); pushProblem(second, "A");
        push(second,"team-a","Accepted","team-code");
        assertThat(jdbc.queryForObject("SELECT signup_team_id FROM submit_record", Long.class)).isEqualTo(91L);
        push(second,"member-a","Accepted","member-code");
        assertThat(jdbc.queryForObject("SELECT user_id FROM submit_record", Long.class)).isEqualTo(9L);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM submit_record", Integer.class)).isEqualTo(1);
    }

    @Test void apiKeysStillRequireBoardPermissionAndNamesAreValidated() throws Exception {
        jdbc.update("UPDATE external_app SET external_board_enabled=false");
        mvc.perform(post("/external/board/7/problems").contentType("application/json")
            .content("{\"api_key\":\"test-key\",\"problems\":[{\"display_id\":\"A\",\"title\":\"blocked\"}]}"))
            .andExpect(jsonPath("$.code").value(403));
        mvc.perform(post("/leaderboard/admin/boards").contentType("application/json").content("{\"eventId\":7,\"name\":\"   \"}"))
            .andExpect(status().isBadRequest());
        assertThat(jdbc.queryForObject("SELECT count(*) FROM external_board", Integer.class)).isEqualTo(1);
    }

    private long create(String name) throws Exception {
        var result = mvc.perform(post("/leaderboard/admin/boards").contentType("application/json")
            .content(json.writeValueAsString(Map.of("eventId",7,"name",name))))
            .andExpect(jsonPath("$.code").value(200)).andReturn();
        long boardId = json.readTree(result.getResponse().getContentAsString()).path("data").path("boardId").asLong();
        assertThat(boardId).isNotEqualTo(7L);
        return boardId;
    }
    private void open(long boardId, String name) {
        ExternalBoardConfigDTO dto = service.getConfig(boardId);
        dto.setName(name); dto.setExternalOpen(true); dto.setUnfrozen(true);
        service.updateConfig(dto);
    }
    private void pushProblem(long boardId, String title) throws Exception {
        mvc.perform(post("/external/board/"+boardId+"/problems").contentType("application/json")
            .content(json.writeValueAsString(Map.of("api_key","test-key","problems",List.of(Map.of("display_id","A","title",title,"score",100,"time_limit",1000,"memory_limit",512))))))
            .andExpect(jsonPath("$.code").value(200));
    }
    private void push(long boardId, String account, String verdict, String code) throws Exception {
        mvc.perform(post("/external/board/"+boardId+"/submissions").contentType("application/json")
            .content(json.writeValueAsString(Map.of("api_key","test-key","submissions",List.of(Map.of(
                "username",account,"problem","A","status",verdict,"score",100,"code",code,"language","cpp",
                "runtime","12 ms","memory","34 KB","rid","same-rid","submit_time","2025-10-01 11:00:00.123"))))))
            .andExpect(jsonPath("$.code").value(200));
    }

