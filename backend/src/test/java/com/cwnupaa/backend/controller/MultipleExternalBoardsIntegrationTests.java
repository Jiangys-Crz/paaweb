    @EnableTransactionManagement(proxyTargetClass = true)
    @MapperScan("com.cwnupaa.backend.mapper")
    static class Config {
        @Bean DataSource dataSource() { return new DriverManagerDataSource("jdbc:h2:mem:multiple_boards;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", ""); }
        @Bean SqlSessionFactory sqlSessionFactory(DataSource datasource) throws Exception {
            var factory = new MybatisSqlSessionFactoryBean(); factory.setDataSource(datasource);
            var plugin = new MybatisPlusInterceptor(); plugin.addInnerInterceptor(new PaginationInnerInterceptor(DbType.H2));
            factory.setPlugins(plugin); return factory.getObject();
        }
        @Bean JdbcTemplate jdbcTemplate(DataSource datasource) { return new JdbcTemplate(datasource); }
        @Bean PlatformTransactionManager transactions(DataSource datasource) { return new DataSourceTransactionManager(datasource); }
        @Bean ExternalBoardService boardService() { return new ExternalBoardService(); }
        @Bean ExternalBoardController boardController() { return new ExternalBoardController(); }
        @Bean ExternalSubmitController submitController() { return new ExternalSubmitController(); }
    }
